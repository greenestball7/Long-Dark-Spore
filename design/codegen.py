#!/usr/bin/env python3
"""Generate src/common/Sheets.gen.h from design/sheets: one C++ struct literal per row."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'design', 'sheets')
S = {f[:-5]: json.load(open(os.path.join(D, f))) for f in sorted(os.listdir(D)) if f.endswith('.json')}
def fl(x): return repr(float(x)) + 'f'
def q(s): return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'
def ident(s): return ''.join(c if c.isalnum() else '_' for c in s)
STAGE = {'cell': 'kStageCell', 'creature': 'kStageCreature'}
def stagemask(lst): return ' | '.join(STAGE[s] for s in lst)
def strlist(lst): return '{' + ', '.join(q(x) for x in lst) + ', nullptr}'
out = ['// GENERATED by design/codegen.py from design/sheets/*.json. Do not edit; change the sheet.',
       '#pragma once', '#include <cstdint>', '', 'namespace Sheets {',
       'enum StageMask : uint32_t { kStageCell = 1, kStageCreature = 2 };', '']
# enums of ids
for name in ('needs', 'weather', 'tld_content'):
    rows = S[name]['rows']
    out.append(f'enum class {ident(name).title().replace("_","")}Id : int {{ ' + ', '.join(ident(r['id']) for r in rows) + f', Count }};')
out.append('')
out += ['struct Need { const char* id; const char* label; float start; float drainIdle; float drainActive; float conditionLossWhenEmpty; uint32_t stages; };',
        'static const Need kNeeds[] = {']
for r in S['needs']['rows']:
    out.append(f'  {{{q(r["id"])}, {q(r["label"])}, {fl(r["start"])}, {fl(r["drain_per_hour_idle"])}, {fl(r["drain_per_hour_active"])}, {fl(r["condition_loss_per_hour_when_empty"])}, {stagemask(r["stages"])}}},')
out.append('};')
out += ['struct Restore { const char* id; int need; const char* trigger; float amount; bool continuous; uint32_t stages; };', 'static const Restore kRestores[] = {']
nidx = {r['id']: i for i, r in enumerate(S['needs']['rows'])}
for r in S['restore']['rows']:
    out.append(f'  {{{q(r["id"])}, {nidx[r["need"]]}, {q(r["trigger"])}, {fl(r["amount"])}, {"true" if r["continuous"] else "false"}, {stagemask(r["stages"])}}},')
out.append('};')
out += ['enum TempKind { kTempAir, kTempWind, kTempBonus };', 'struct TempTerm { const char* id; TempKind kind; float celsius; const char* appliesWhen; uint32_t stages; };', 'static const TempTerm kTempTerms[] = {']
for r in S['temperature']['rows']:
    out.append(f'  {{{q(r["id"])}, kTemp{r["kind"].title()}, {fl(r["celsius"])}, {q(r["applies_when"])}, {stagemask(r["stages"])}}},')
out.append('};')
rt = S['temperature']['rates']
out += [f'static const float kWarmthDrainPerDegree = {fl(rt["warmth_drain_per_hour_per_degree_below_zero"])};',
        f'static const float kWarmthGainPerDegree = {fl(rt["warmth_gain_per_hour_per_degree_above_zero"])};',
        f'static const float kHypothermiaAfterHours = {fl(rt["hypothermia_after_hours_at_zero_warmth"])};',
        f'static const float kHypothermiaMultiplier = {fl(rt["hypothermia_condition_multiplier"])};']
widx = {r['id']: i for i, r in enumerate(S['weather']['rows'])}
cidx = {r['id']: i for i, r in enumerate(S['tld_content']['rows'])}
out += ['struct Weather { const char* id; const char* label; float minHours; float maxHours; int next[4]; float overlayAlpha; int sound; uint32_t stages; };', 'static const Weather kWeather[] = {']
for r in S['weather']['rows']:
    nx = [widx[n] for n in r['next']] + [-1] * (4 - len(r['next']))
    out.append(f'  {{{q(r["id"])}, {q(r["label"])}, {fl(r["min_hours"])}, {fl(r["max_hours"])}, {{{", ".join(map(str, nx))}}}, {fl(r["overlay_alpha"])}, {cidx[r["sound"]]}, {stagemask(r["stages"])}}},')
out.append('};')
out += ['enum AudioRole { kRoleAmbience, kRoleOneshot, kRoleMusic };',
        'struct Content { const char* id; AudioRole role; const char* keywords[12]; const char* exclude[8]; const char* fallback; bool loop; float volume; uint32_t stages; };', 'static const Content kContent[] = {']
for r in S['tld_content']['rows']:
    out.append(f'  {{{q(r["id"])}, kRole{r["role"].title()}, {strlist(r["keywords"])}, {strlist(r["exclude"])}, {q(r["fallback"])}, {"true" if r["loop"] else "false"}, {fl(r["volume"])}, {stagemask(r["stages"])}}},')
out.append('};')
out += ['enum HudKind { kHudPanel, kHudBar, kHudText, kHudOverlay };',
        'struct HudElem { const char* id; HudKind kind; const char* binds; float x, y, w, h; uint8_t color[4]; uint32_t stages; };', 'static const HudElem kHud[] = {']
for r in S['hud']['rows']:
    c = r['color']
    out.append(f'  {{{q(r["id"])}, kHud{r["kind"].title()}, {q(r["binds"])}, {r["x"]}, {r["y"]}, {r["w"]}, {r["h"]}, {{{c[0]}, {c[1]}, {c[2]}, {c[3]}}}, {stagemask(r["stages"])}}},')
out.append('};')
for r in S['timing']['rows'] + S['thresholds']['rows']:
    out.append(f'static const float k_{ident(r["id"])} = {fl(r["value"])};  // {r["unit"]}')
out += ['struct Stage { const char* id; uint32_t mask; bool active; uint32_t needsMask; };', 'static const Stage kStages[] = {']
for r in S['stages']['rows']:
    nm = ' | '.join(f'(1u << {nidx[n]})' for n in r['needs'])
    out.append(f'  {{{q(r["id"])}, {STAGE[r["id"]]}, {"true" if r["active"] else "false"}, {nm}}},')
out.append('};')
out += ['template<class T, int N> constexpr int Count(const T (&)[N]) { return N; }', '}  // namespace Sheets', '']
os.makedirs(os.path.join(ROOT, 'src', 'common'), exist_ok=True)
open(os.path.join(ROOT, 'src', 'common', 'Sheets.gen.h'), 'w').write('\n'.join(out))
print('wrote src/common/Sheets.gen.h')
